import type { FilesEvidence, SizeStatsEvidence, SizeStatsFile } from "@esbenwiberg/repofit/sdk";

export const SOURCE_OR_SCHEMA =
  /\.(?:ts|tsx|js|jsx|mjs|cjs|py|go|rs|java|kt|cs|json|ya?ml|graphql|proto)$/i;
export const GENERATED_PATH =
  /(?:^|\/)(?:generated|__generated__|gen|autogen|openapi-client|graphql\/generated)(?:\/|$)|(?:^|\/)[^/]+\.(?:gen|generated|pb)\.[^.]+$/i;
export const GENERATED_HEADER =
  /^\s*(?:\/\/|\/\*|\*|#|<!--)\s*(?:@generated|code generated|.*do not edit|auto-generated)/im;
export const SKIP_DIRS = /(?:^|\/)(?:node_modules|coverage|\.git)\//;
export const TEST_OR_FIXTURE_PATH =
  /(?:\.test\.|\.spec\.|__tests__|^tests?\/|\/tests?\/|^fixtures\/|\/fixtures\/|^examples\/|\/examples\/)/i;

/** Files read for a generated header; larger ones are judged by path alone. */
const HEADER_READ_LIMIT = 100_000;

/**
 * Lockfiles `size_stats` marks generated by default. They are regenerated by
 * a package manager, not a code generator, so a harness edit deny on them is
 * nobody's practice and they are left out of the generated-path families.
 * Mirrors `DEFAULT_GENERATED_FILENAMES` in the engine's size-stats gatherer.
 */
const LOCKFILES = new Set([
  "package-lock.json",
  "yarn.lock",
  "pnpm-lock.yaml",
  "npm-shrinkwrap.json",
  "bun.lockb",
  "bun.lock",
  "Cargo.lock",
  "Gemfile.lock",
  "composer.lock",
  "poetry.lock",
  "Pipfile.lock",
  "uv.lock",
  "flake.lock",
  "mix.lock",
  "pubspec.lock",
  "go.sum",
  "packages.lock.json",
]);

function basename(path: string): string {
  return path.slice(path.lastIndexOf("/") + 1);
}

/** Source or schema files that are neither skipped by directory nor tests, fixtures or examples. */
export function sourceCandidates(size: SizeStatsEvidence): SizeStatsFile[] {
  return size.files
    .filter(
      (f) =>
        SOURCE_OR_SCHEMA.test(f.path) &&
        !SKIP_DIRS.test(`/${f.path}`) &&
        !TEST_OR_FIXTURE_PATH.test(f.path),
    )
    .sort((a, b) => a.path.localeCompare(b.path));
}

/** Whether a file looks generated by its path, or by a generator header when the path is silent. */
export async function looksGenerated(file: SizeStatsFile, files: FilesEvidence): Promise<boolean> {
  if (GENERATED_PATH.test(file.path)) return true;
  if (file.bytes >= HEADER_READ_LIMIT) return false;
  const text = await files.readText(file.path);
  return GENERATED_HEADER.test(text?.slice(0, 1_000) ?? "");
}

/**
 * Every tracked source or schema file that is generated: marked so in
 * `size_stats` (linguist-generated), or recognisable by path or header.
 * Lockfiles are excluded.
 */
export async function generatedFiles(
  size: SizeStatsEvidence,
  files: FilesEvidence,
): Promise<string[]> {
  const out: string[] = [];
  for (const f of sourceCandidates(size)) {
    if (LOCKFILES.has(basename(f.path))) continue;
    if (f.generated || (await looksGenerated(f, files))) out.push(f.path);
  }
  return out;
}
